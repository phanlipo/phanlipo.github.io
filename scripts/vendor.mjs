function writeIndex() {
  // Versions, licences and purposes are listed once, in NOTICE.md (generated by build.mjs).
  writeFileSync(join(VENDOR, 'README.md'), `# Fremdbibliotheken (vendor)

Automatisch erzeugt von \`scripts/vendor.mjs\` – nicht von Hand ändern.

Die Bibliotheken liegen lokal im Repository, damit die Seiten ohne CDN und offline (PWA) funktionieren.
Jeder Ordner enthält die Original-Lizenz (\`LICENSE\`).
**Übersicht mit Version, Lizenz, Copyright und Zweck: [\`NOTICE.md\`](../../NOTICE.md).**
Herkunft, Prüfsummen und welche App was nutzt: SBOM [\`sbom.cdx.json\`](../../sbom.cdx.json).

## Aktualisieren

- Prüfen: \`node scripts/vendor.mjs --check\` – Updates, Pflege und Schwachstellen (läuft monatlich als GitHub Action und öffnet bei Bedarf ein Issue)
- Aktualisieren: \`node scripts/vendor.mjs --update <name>\`, danach die betroffenen Seiten testen
`);
}

// Version a dependent entry must have, according to the parent library's package.json
async function requiredVersion(e) {
  const parent = config[e.versionFrom.entry];
  const info = await npmVersionInfo(parent.package, parent.version);
  const v = (info.dependencies || {})[e.versionFrom.dependency];
  if (!v) throw new Error(`${parent.package}@${parent.version} has no dependency ${e.versionFrom.dependency}`);
  return v.replace(/^[\^~=]/, '');
}

/* ---------- Check: updates, maintenance, vulnerabilities ---------- */

// JSON from an API; null for 404 (unknown). Retries network errors and 5xx/429.
async function getJson(url, init = {}) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, init);
      if (res.status === 404) return null;
      if (res.ok) return await res.json();
      if (attempt >= 3 || (res.status < 500 && res.status !== 429)) throw new Error(`${res.status} ${new URL(url).host}`);
    } catch (err) {
      if (attempt >= 3 || /^\d{3} /.test(err.message)) throw err;
    }
    await new Promise(r => setTimeout(r, 2000 * attempt));
  }
}
const enc = encodeURIComponent;
const DEPSDEV = 'https://api.deps.dev/v3';
const githubHeaders = process.env.GITHUB_TOKEN
  ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}`, accept: 'application/vnd.github+json' } : { accept: 'application/vnd.github+json' };

// Facts for assessHealth (lib.mjs) from deps.dev (npm data + OpenSSF Scorecard) and GitHub
async function healthFacts(e) {
  const pkg = await getJson(`${DEPSDEV}/systems/npm/packages/${enc(e.package)}`);
  if (!pkg) throw new Error(`${e.package} nicht auf deps.dev gefunden`);
  const versions = pkg.versions || [];
  const used = versions.find(v => v.versionKey.version === e.version);
  const latest = versions.find(v => v.isDefault);
  const f = {
    deprecated: used?.isDeprecated ? used.deprecatedReason || 'deprecated' : '',
    latestDeprecated: latest?.isDeprecated ? latest.deprecatedReason || 'deprecated' : '',
    lastRelease: versions.map(v => v.publishedAt).filter(Boolean).sort().pop() || null,
    archived: null, lastCommit: null, maintained: null, repo: null,
  };
  const ver = await getJson(`${DEPSDEV}/systems/npm/packages/${enc(e.package)}/versions/${enc(e.version)}`);
  const projects = ver?.relatedProjects || [];
  f.repo = (projects.find(p => p.relationType === 'SOURCE_REPO') || projects[0])?.projectKey.id || null;
  if (f.repo) {
    const project = await getJson(`${DEPSDEV}/projects/${enc(f.repo.toLowerCase())}`);
    const m = project?.scorecard?.checks?.find(c => c.name === 'Maintained');
    if (m && m.score >= 0) f.maintained = m.score;
    if (m && /archived/i.test(m.reason || '')) f.archived = true;
    const gh = f.repo.match(/^github\.com\/([^/]+\/[^/]+)$/);
    if (gh) {
      // Unknown without access (e.g. rate limit) – the Scorecard then stands in
      const r = await getJson(`https://api.github.com/repos/${gh[1]}`, { headers: githubHeaders }).catch(() => null);
      if (r) { f.archived = !!r.archived || f.archived === true; f.lastCommit = r.pushed_at || null; }
    }
  }
  return f;
}

// Known vulnerabilities (OSV) of every library: Map(name -> [{ id, summary, severity, url }])
async function vulnerabilities(entries) {
  const res = await getJson('https://api.osv.dev/v1/querybatch', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ queries: entries.map(([, e]) => ({ package: { name: e.package, ecosystem: 'npm' }, version: e.version })) }),
  });
  const out = new Map();
  for (const [i, [name]] of entries.entries()) {
    const list = [];
    for (const { id } of res.results[i]?.vulns || []) {
      const v = await getJson(`https://api.osv.dev/v1/vulns/${enc(id)}`);
      list.push({ id, summary: v?.summary || '', severity: v ? vulnSeverity(v) : 'UNKNOWN', url: `https://osv.dev/vulnerability/${id}` });
    }
    out.set(name, list);
  }
  return out;
}

const daysSince = iso => (Date.now() - Date.parse(iso)) / 864e5;
const dateDe = iso => iso ? iso.slice(0, 10) : '?';
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

async function check() {
  const entries = Object.entries(config);
  const base = arg('--base') ? JSON.parse(readFileSync(arg('--base'), 'utf8')) : null;
  // Pull request: only new or changed libraries can block
  const changed = new Set(base ? entries.filter(([n, e]) => base[n]?.package !== e.package || base[n]?.version !== e.version).map(([n]) => n) : []);

  const outdated = [], health = new Map();
  for (const [name, e] of entries) {
    if (e.versionFrom) {
      const need = await requiredVersion(e);
      if (need !== e.version) outdated.push({ name, pkg: e.package, current: e.version, latest: need, major: false, note: `vorgegeben von ${e.versionFrom.entry}` });
    } else {
      const latest = await npmLatest(e.package);
      // Breaking per semver: major changed, or minor changed while major is 0 (0.x)
      const [a1, a2] = e.version.split('.').map(Number), [b1, b2] = latest.split('.').map(Number);
      if (latest !== e.version) {
        const published = await publishedAt(e.package, latest);
        const wait = published && daysSince(published) < COOLDOWN_DAYS;
        outdated.push({ name, pkg: e.package, current: e.version, latest, major: b1 !== a1 || (a1 === 0 && b2 !== a2),
          note: wait ? `neu seit ${dateDe(published)} – \`--update\` übernimmt sie nach ${COOLDOWN_DAYS} Tagen` : '' });
      }
    }
    let h;
    try {
      h = { ...assessHealth(await healthFacts(e), { exception: e.maintenanceException }) };
    } catch (err) {
      h = { level: 'warn', reasons: [`Pflege nicht prüfbar: ${err.message}`] };
    }
    health.set(name, h);
    const o = outdated.find(x => x.name === name);
    console.log(`${{ ok: '✓', warn: '!', fail: '✗' }[h.level]} ${name} ${e.version}${o ? ` (neu: ${o.latest})` : ''}${h.reasons.length ? ' – ' + h.reasons.join('; ') : ''}`);
  }

  let vulns = new Map(), vulnError = null;
  try { vulns = await vulnerabilities(entries); } catch (err) { vulnError = err.message; }
  for (const [name, list] of vulns) for (const v of list) console.log(`✗ ${name}: ${v.id} (${v.severity}) ${v.summary}`);
  if (vulnError) console.log(`! Schwachstellen nicht prüfbar: ${vulnError}`);

  // What blocks a pull request
  const blocking = [];
  for (const n of changed) {
    if (health.get(n).level === 'fail') blocking.push(`**${n}** – nicht gepflegt: ${health.get(n).reasons.join('; ')}`);
    for (const v of (vulns.get(n) || []).filter(v => vulnBlocks(v.severity))) blocking.push(`**${n}** – Schwachstelle [${v.id}](${v.url}) (${v.severity})`);
  }
  if (base && changed.size && vulnError) blocking.push(`Schwachstellen nicht prüfbar (${vulnError}) – Check erneut starten`);

  const md = arg('--markdown');
  if (md) writeFileSync(md, report({ entries, health, vulns, vulnError, outdated, base, changed, blocking }));
  return { outdated, blocking, health, vulns };
}

async function publishedAt(pkg, version) {
  const v = await getJson(`${DEPSDEV}/systems/npm/packages/${enc(pkg)}/versions/${enc(version)}`).catch(() => null);
  return v?.publishedAt || null;
}

function report({ entries, health, vulns, vulnError, outdated, base, changed, blocking }) {
  const sec = [];
  const pkgLink = e => `[\`${e.package}\`](https://www.npmjs.com/package/${e.package})`;
  if (base) {
    sec.push(changed.size
      ? `### Neue oder geänderte Bibliotheken\n\n${blocking.length ? `⛔ **Blockiert:**\n\n${blocking.map(b => `- ${b}`).join('\n')}` : '✅ Gepflegt und ohne bekannte hohe/kritische Schwachstellen.'}\n\n| Name | Paket | Version | Pflege | Schwachstellen |\n|---|---|---|---|---|\n` +
        [...changed].map(n => {
          const e = config[n], h = health.get(n), v = vulns.get(n) || [];
          return `| ${n} | ${pkgLink(e)} | ${e.version} | ${{ ok: '✅', warn: '⚠️', fail: '⛔' }[h.level]} ${cell(h.reasons.join('; '))} | ${v.length ? v.map(x => `[${x.id}](${x.url}) (${x.severity})`).join(', ') : vulnError ? '?' : '–'} |`;
        }).join('\n')
      : '### Bibliotheken\n\nKeine neue oder geänderte Bibliothek.');
  }
  const rows = level => entries.filter(([n]) => health.get(n).level === level)
    .map(([n, e]) => `| ${n} | ${pkgLink(e)} | ${e.version} | ${cell(health.get(n).reasons.join('; '))} |`);
  const fail = rows('fail'), warn = rows('warn');
  if (fail.length) sec.push(`### ⛔ Nicht mehr gepflegt – ersetzen\n\n| Name | Paket | Version | Befund |\n|---|---|---|---|\n${fail.join('\n')}`);
  const vulnRows = entries.flatMap(([n, e]) => (vulns.get(n) || []).map(v => `| ${n} | ${pkgLink(e)} | ${e.version} | [${v.id}](${v.url}) | ${v.severity} | ${cell(v.summary)} |`));
  if (vulnRows.length) sec.push(`### 🛡️ Bekannte Schwachstellen (OSV)\n\n| Name | Paket | Version | ID | Schwere | Beschreibung |\n|---|---|---|---|---|---|\n${vulnRows.join('\n')}\n\nBeheben: auf eine Version ohne die Schwachstelle aktualisieren oder die Bibliothek ersetzen.`);
  if (vulnError) sec.push(`### 🛡️ Schwachstellen nicht prüfbar\n\n${vulnError}`);
  if (warn.length) sec.push(`### ⚠️ Pflege beobachten\n\n| Name | Paket | Version | Befund |\n|---|---|---|---|\n${warn.join('\n')}\n\nBewusst behalten: \`"maintenanceException": { "reason": "…", "until": "JJJJ-MM" }\` in \`scripts/vendor.json\`.`);
  if (outdated.length) sec.push(`### ⬆️ Neuere Versionen\n\n| Name | Paket | Aktuell | Neu | Hinweis |\n|---|---|---|---|---|\n${outdated.map(o => `| ${o.name} | [\`${o.pkg}\`](https://www.npmjs.com/package/${o.pkg}?activeTab=versions) | ${o.current} | ${o.latest} | ${[o.major ? '⚠️ kann inkompatibel sein – Changelog prüfen' : '', o.note].filter(Boolean).join('; ')} |`).join('\n')}\n\n**Aktualisieren:** \`node scripts/vendor.mjs --update <name>\`, dann die betroffenen Seiten testen (Zweck siehe \`NOTICE.md\`).`);
  if (!sec.length) return '';
  return `Prüfung der Bibliotheken in \`assets/vendor/\` (\`scripts/vendor.json\`): Pflege (npm, [deps.dev](https://deps.dev)/OpenSSF Scorecard, GitHub), Schwachstellen ([OSV](https://osv.dev)), Updates. Regeln: \`AGENTS.md\` → „Bibliotheken: Pflege & Sicherheit“ (Fehler: deprecated, archiviert oder > ${HEALTH.failReleaseMonths} Monate kein Release und > ${HEALTH.failCommitMonths} Monate kein Commit; Warnung: > ${HEALTH.warnReleaseMonths} Monate kein Release).\n\n${sec.join('\n\n')}\n`;
}

if (flag('--check')) {
  const { outdated, blocking, health, vulns } = await check();
  const n = level => [...health.values()].filter(h => h.level === level).length;
  console.log(`${outdated.length} Update(s), ${n('fail')} nicht gepflegt, ${n('warn')} Warnung(en), ${[...vulns.values()].flat().length} Schwachstelle(n).`);
  if (blocking.length) {
    console.error(`Blockiert:\n${blocking.map(b => `  ${b.replace(/\*\*/g, '')}`).join('\n')}`);
    process.exit(1);
  }
} else {
  const upd = arg('--update');
  if (upd) {
    const names = upd === 'all' ? Object.keys(config) : [upd];
    for (const n of names) {
      if (!config[n]) throw new Error(`Unbekannt: ${n}`);
      if (config[n].versionFrom) continue;
      const latest = await npmLatest(config[n].package);
      if (latest === config[n].version) continue;
      const published = await publishedAt(config[n].package, latest);
      if (!flag('--no-cooldown') && published && daysSince(published) < COOLDOWN_DAYS) {
        console.log(`… ${n} ${latest} erst seit ${dateDe(published)} veröffentlicht – bleibt bei ${config[n].version} (Wartezeit ${COOLDOWN_DAYS} Tage, sofort: --no-cooldown)`);
        continue;
      }
      config[n].version = latest;
    }
    // Dependent entries follow their parent (also when only the parent was updated)
    for (const e of Object.values(config)) if (e.versionFrom) e.version = await requiredVersion(e);
  }
  for (const [name, e] of Object.entries(config)) {
    if (flag('--force') || installedVersion(name) !== e.version || !e.integrity) await download(name, e);
    else console.log(`= ${name} ${e.version}`);
  }
  writeFileSync(CONFIG, JSON.stringify(config, null, 2) + '\n');
  writeIndex();
  console.log('Danach: node scripts/build.mjs (NOTICE.md, SBOM, Offline-Cache)');
}
